#!/usr/bin/env python3
"""N°98 Maps: build the multilingual theme files.

    python3 tools/i18n/build.py            build shopify/sections + snippets
    python3 tools/i18n/build.py --missing  list texts that have no translation yet

Sources (English) live in shopify/src/. Translations live in tools/i18n/<lang>.json:
  "text": { "<English text>": "<translation>" }   whole text segments between tags,
          and the attributes alt, aria-label, placeholder, title
  "raw":  { "<file name>": [["old", "new"], ...] } literal replacements (scripts, urls)
Links that start with "/" get the language prefix ("/nl/..."), so visitors stay in
their language. The homepage is too big to hold every language in one file, so
each language becomes its own snippet (n98-home--<lang>.liquid).

Also merges tools/i18n/locale.<lang>.json into the theme locale files
(shopify/locales/<lang>.json) under the key "n98", used by sections that
translate with the | t filter (city pages, header switches).
"""
import json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
SRC = ROOT / 'shopify' / 'src'
I18N = ROOT / 'tools' / 'i18n'
LANGS = [p.stem for p in sorted(I18N.glob('??.json'))]
ATTRS = ('alt', 'aria-label', 'placeholder', 'title')
SPLIT = re.compile(r'(<script\b.*?</script>|<style\b.*?</style>|\{%-?\s*(?:schema|comment)\s*-?%\}.*?\{%-?\s*end(?:schema|comment)\s*-?%\}|\{%.*?%\}|\{\{.*?\}\}|<[^>]+>)', re.S)
ATTR_RE = re.compile(r'\b(' + '|'.join(ATTRS) + r')="([^"]*)"')


def norm(t):
    return re.sub(r'\s+', ' ', t).strip()


def wanted(t):
    return bool(re.search(r'[A-Za-z]{2}', t)) and not t.startswith('=')


def segments(src):
    """Yield (kind, text) for every translatable piece."""
    for part in SPLIT.split(src):
        if not part:
            continue
        if part.startswith('<') and not part.startswith(('<script', '<style')):
            for m in ATTR_RE.finditer(part):
                if wanted(m.group(2)) and '{{' not in m.group(2):
                    yield 'attr', norm(m.group(2))
        elif not part.startswith(('<', '{%', '{{')):
            if wanted(part):
                yield 'text', norm(part)


def translate(src, d, raw, lang):
    for old, new in raw:
        if old not in src:
            raise SystemExit('raw replacement not found: %r' % old[:80])
        src = src.replace(old, new)
    out = []
    for part in SPLIT.split(src):
        if not part:
            continue
        if part.startswith('<') and not part.startswith(('<script', '<style')):
            def rep(m):
                v = norm(m.group(2))
                return '%s="%s"' % (m.group(1), d.get(v, m.group(2)))
            part = ATTR_RE.sub(rep, part)
            # keep visitors in their language
            part = re.sub(r'\bhref="/(?!/)', 'href="/%s/' % lang, part)
            part = part.replace('href="/%s/"' % lang, 'href="/%s"' % lang)
        elif not part.startswith(('<', '{%', '{{')):
            k = norm(part)
            if k in d:
                lead = part[:len(part) - len(part.lstrip())]
                trail = part[len(part.rstrip()):]
                part = lead + d[k] + trail
        out.append(part)
    return ''.join(out)


def split_file(src):
    """preamble ({%- liquid %} / comment at the top), body, schema."""
    m = re.search(r'\{%-?\s*schema\s*-?%\}.*?\{%-?\s*endschema\s*-?%\}\s*$', src, re.S)
    schema = m.group(0) if m else ''
    body = src[:m.start()] if m else src
    pre = ''
    while True:
        m2 = re.match(r'\s*(\{%-?\s*comment\s*-?%\}.*?\{%-?\s*endcomment\s*-?%\}|\{%-?\s*liquid\b.*?-?%\})', body, re.S)
        if not m2:
            break
        pre += m2.group(0)
        body = body[m2.end():]
    return pre, body, schema


def load(lang):
    j = json.loads((I18N / (lang + '.json')).read_text(encoding='utf-8'))
    return {norm(k): v for k, v in j.get('text', {}).items()}, j.get('raw', {})


def build():
    tr = {l: load(l) for l in LANGS}
    written = []
    for f in sorted(SRC.rglob('*.liquid')):
        kind = f.parent.name  # sections / snippets
        src = f.read_text(encoding='utf-8')
        pre, body, schema = split_file(src)
        if f.name == 'n98-maps-home.liquid':
            # every language in its own snippet; the section picks one
            body = body.replace('{{ section.id }}', '{{ n98_sid }}')
            params = "n98_configurator_url: n98_configurator_url, n98_app_url: n98_app_url, n98_sid: section.id"
            parts = [pre, '\n{%- case request.locale.iso_code -%}\n']
            for l in LANGS:
                d, raw = tr[l]
                name = 'n98-home--%s' % l
                (ROOT / 'shopify' / 'snippets' / (name + '.liquid')).write_text(
                    '{%- comment -%} GENERATED by tools/i18n/build.py from shopify/src/sections/n98-maps-home.liquid {%- endcomment -%}\n'
                    + translate(body, d, raw.get(f.name, []), l), encoding='utf-8')
                written.append('snippets/' + name + '.liquid')
                parts.append("  {%%- when '%s' -%%}{%% render '%s', %s %%}\n" % (l, name, params))
            (ROOT / 'shopify' / 'snippets' / 'n98-home--en.liquid').write_text(
                '{%- comment -%} GENERATED by tools/i18n/build.py from shopify/src/sections/n98-maps-home.liquid {%- endcomment -%}\n' + body, encoding='utf-8')
            written.append('snippets/n98-home--en.liquid')
            parts.append("  {%%- else -%%}{%% render 'n98-home--en', %s %%}\n{%%- endcase -%%}\n\n" % params)
            out = ''.join(parts) + schema
        else:
            out = pre + '\n{%- case request.locale.iso_code -%}\n'
            for l in LANGS:
                d, raw = tr[l]
                out += "{%%- when '%s' -%%}\n%s\n" % (l, translate(body, d, raw.get(f.name, []), l).strip('\n'))
            out += '{%- else -%}\n' + body.strip('\n') + '\n{%- endcase -%}\n' + ('\n' + schema if schema else '')
        dest = ROOT / 'shopify' / kind / f.name
        dest.write_text(out, encoding='utf-8')
        written.append(kind + '/' + f.name)
    # locale files
    for base in sorted((ROOT / 'shopify' / 'locales-base').glob('*.json')):
        lang = base.stem.split('.')[0]
        extra = I18N / ('locale.%s.json' % lang)
        if not extra.exists():
            continue
        txt = base.read_text(encoding='utf-8')
        # these files may hold comments, so add the block as text before the last brace
        block = json.dumps(json.loads(extra.read_text(encoding='utf-8')), indent=2, ensure_ascii=False).replace('\n', '\n  ')
        i = txt.rstrip().rindex('}')
        out_txt = txt[:i].rstrip() + ',\n  "n98": ' + block + '\n}\n'
        (ROOT / 'shopify' / 'locales').mkdir(exist_ok=True)
        (ROOT / 'shopify' / 'locales' / base.name).write_text(out_txt, encoding='utf-8')
        written.append('locales/' + base.name)
    return written


def missing():
    for l in LANGS:
        d, _ = load(l)
        seen = set()
        for f in sorted(SRC.rglob('*.liquid')):
            for kind, t in segments(split_file(f.read_text(encoding='utf-8'))[1]):
                if t not in d and t not in seen:
                    seen.add(t)
                    print('%s\t%s\t%s' % (l, f.name, t))


if __name__ == '__main__':
    if '--missing' in sys.argv:
        missing()
    else:
        for w in build():
            print('wrote', w)
